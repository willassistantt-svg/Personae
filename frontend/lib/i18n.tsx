type LanguageValue = { locale: Locale; setLocale: (locale: Locale) => void; t: (key: string) => string };

const LanguageContext = createContext<LanguageValue | null>(null);

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>("pt");
  useEffect(() => {
    const saved = window.localStorage.getItem("personae-locale");
    if (saved === "en" || saved === "pt") {
      setLocaleState(saved);
    }
  }, []);
  const value = useMemo<LanguageValue>(
    () => ({
      locale,
      setLocale: (next) => {
        window.localStorage.setItem("personae-locale", next);
        setLocaleState(next);
        document.documentElement.lang = next === "pt" ? "pt-BR" : "en";
      },
      t: (key) => translate(locale, key),
    }),
    [locale],
  );
  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

export function useI18n() {
  const value = useContext(LanguageContext);
  if (!value) {
    throw new Error("LanguageProvider is missing");
  }
  return value;
}
